from rat.arabic.fonts import FontManager
from rat.domain.arabic import CompatibilityProfile, RuntimeOptions

RUNTIME_PATH = "game/tl/arabic/arabic_runtime.rpy"

RUNTIME_CODE = """# Generated by RAT. Logical Unicode is never reversed or reshaped here.
# Disable: create game/tl/arabic/rat_runtime.disabled and restart the game.
init 999 python in rat_arabic_runtime:
    import renpy
    settings = __RAT_SETTINGS__
    _original_rtl = renpy.config.rtl
    active = False
    status = "inactive"

    def is_enabled():
        return (not getattr(renpy.store.persistent, "_rat_arabic_runtime_disabled", False)
                and not renpy.exports.loadable("tl/arabic/rat_runtime.disabled"))

    def apply():
        global active, status
        # Initial style construction must remain the game's unmodified baseline.
        if renpy.translation.style_backup is None:
            return
        if active:
            renpy.config.rtl = _original_rtl
        active = False
        status = "inactive"
        if renpy.game.preferences.language != "arabic" or not is_enabled():
            return
        actual = tuple(renpy.version_tuple[:3])
        if actual != tuple(settings["target_version"]):
            status = "version_mismatch"
            raise Exception("RAT Arabic runtime: engine version differs from the export target.")
        font = renpy.text.font.FontGroup()
        for filename, first, last in settings["font_ranges"]:
            font.add(filename, first, last)
        font.add(settings["default_font"], None, None)
        renpy.config.rtl = settings["direction"] != "ltr"
        for name, size in settings["styles"].items():
            target = getattr(renpy.store.style, name)
            target.font = font
            target.shaper = "harfbuzz"
            if size is not None:
                target.size = size
            if settings["reading_order"]:
                target.reading_order = settings["direction"]
            if settings["align_interfaces"] or name in ("say_dialogue", "say_label"):
                target.textalign = 0.0 if settings["direction"] == "ltr" else 1.0
                if name != "default":
                    target.xalign = 0.0 if settings["direction"] == "ltr" else 1.0
        active = True
        status = "native_active"

    def set_enabled(value):
        renpy.store.persistent._rat_arabic_runtime_disabled = not bool(value)
        renpy.exports.change_language(renpy.game.preferences.language, force=True, rebuild=True)
        renpy.exports.restart_interaction()

    # Create named styles before Ren'Py takes its baseline style snapshot.
    for name in settings["styles"]:
        getattr(renpy.store.style, name)
    # Called after deferred styles too, and for every language and preference rebuild.
    renpy.config.build_styles_callbacks.append(apply)
"""


class StyleGenerator:
    def generate(
        self,
        options: RuntimeOptions,
        profile: CompatibilityProfile,
        fonts,
        paths,
        *,
        direction="auto",
    ) -> str:
        if not profile.supported or not profile.version:
            raise ValueError("unsupported_arabic_runtime")
        sizes = options.sizes
        styles = {"default": None}
        for names, size in (
            (("say_dialogue", "say_thought", "nvl_dialogue", "input"), sizes.dialogue),
            (("say_label", "nvl_label", "history_name_text"), sizes.names),
            (("choice_button_text", "nvl_button_text"), sizes.choices),
            (("history_text",), sizes.history),
            (
                (
                    "pref_label_text",
                    "pref_button_text",
                    "pref_text",
                    "button_text",
                    "label_text",
                    "check_button_text",
                    "radio_button_text",
                    "navigation_button_text",
                ),
                sizes.preferences,
            ),
        ):
            styles.update({name: size for name in names})
        data = {
            "target_version": tuple(map(int, profile.version.split("."))),
            "direction": "wrtl" if direction == "auto" else direction,
            "reading_order": profile.reading_order,
            "align_interfaces": options.align_interfaces,
            "styles": styles,
            "default_font": paths[fonts[0].sha256],
            "font_ranges": [
                (paths[digest], first, last)
                for digest, first, last in FontManager().assignments(fonts)
            ],
        }
        return RUNTIME_CODE.replace("__RAT_SETTINGS__", repr(data))
